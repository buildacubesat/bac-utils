"""The catalog showcase projects: one generated KiCad project per part catalog.

``showcase ROOT`` writes ``<catalog folder>/showcase/`` for the passives, the
ICs and the other parts: a KiCad 10 project that places every catalog row
once – a root sheet, one sheet per section, a board with every
footprint on a grid – plus ``showcase-report.md`` listing the rows without a
library symbol, footprint or 3D model. The projects are a visual index, and
the library audit counts their placements like any project's.

Everything is text built here: symbols and footprints are copied from the
library by span (:mod:`bac_common.sexp`), UUIDs are ``uuid5`` of the row id
(of file name and position for sheets, labels and no-connect flags),
dates and revisions come from the catalog README, so an unchanged catalog
regenerates byte for byte. No ``pcbnew``, no ``kicad-cli``.

The rules (decided 2026-11-14):

* A passive places ``bac R``, ``bac C``, ``bac C Polarized`` or
  ``bac R Shunt`` with the row's value and the bac library footprint derived
  from its package (``R-0603``); where the library has none, the catalog's
  own footprint and a report line.
* An IC or other part places the live library symbol whose
  ``Manufacturer PN`` is the row's; else the symbol a board's sheet draws
  that part number with (often a KiCad stock symbol), taken from the sheet's
  cache; else the symbol of the slot's reference
  row when the row is a drop-in; else ``bac Catalog Placeholder``. The row's
  part number is written into the instance. Further live symbols carrying
  the same part number are placed next to it.
* A row without a footprint is placed in the schematic only.
"""

