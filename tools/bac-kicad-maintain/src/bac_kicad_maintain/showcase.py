def _ours(project: str) -> bool:
    """Whether a ``.kicad_pro`` is still the minimal file this tool writes; KiCad adds its own keys on saving."""
    try:
        data = json.loads(project)
    except ValueError:
        return False
    return isinstance(data, dict) and set(data) == {"meta", "sheets", "text_variables"}


def _file_op(path: Path, text: str, *, keep_existing: bool = False) -> FileOp:
    if not path.is_file():
        return FileOp(path, text, "new")
    with path.open(encoding="utf-8", newline="") as f:
        original = f.read()
    if keep_existing and not _ours(original):
        return FileOp(path, None, "kept", original)
    return FileOp(path, text, "unchanged" if original == text else "changed", original)


def _stale(folder: Path, keep: set[str]) -> list[FileOp]:
    """Generated sheets of an earlier run that this one no longer writes."""
    out = []
    marker = f"(generator {quoted(GENERATOR)})"
    for path in sorted(folder.glob("*.kicad_sch")) if folder.is_dir() else []:
        if path.name in keep:
            continue
        with path.open(encoding="utf-8", newline="") as f:
            head = f.read(400)
        if marker in head:
            out.append(FileOp(path, None, "remove", None))
    return out


def _build_one(catalog: str, folder: Path, rows: list[dict[str, str]], lib: Library, settings: Settings) -> Showcase:
    version, date = readme_version(folder)
    show = Showcase(catalog, folder / "showcase", f"bac-catalog-{catalog}-showcase", version, date)
    show.company = settings.titleblock_company
    show.library = Path(settings.audit_library).as_posix()
    show.symbol_nickname = lib.symbol_nickname
    show.root_uuid = uid("root", catalog)
    seen: dict[str, int] = defaultdict(int)
    for row in rows:
        seen[row["id"]] += 1
    duplicates = sorted(i for i, n in seen.items() if n > 1)
    if duplicates:
        raise ShowcaseError(f"The {catalog} catalog repeats the id {duplicates[0]!r}.", "Run check ROOT --catalog.")
    if catalog == "passives":
        show.sheets = _passive_sheets(rows, lib, show.findings)
    else:
        show.sheets = _part_sheets(catalog, rows, lib, show.findings)
    for page, sheet in enumerate(show.sheets, start=2):
        sheet.uuid = uid("sheet", catalog, sheet.file)
        sheet.symbol_uuid = uid("sheet-symbol", catalog, sheet.file)
        sheet.page = page
        _position(sheet)
    _annotate(show.sheets)
    placements = show.placements
    for placement in placements:
        _resolve_footprint(lib, placement, show.findings)
    board, on_board = _board_text(show, settings)
    how = defaultdict(int)
    for placement in placements:
        how[placement.how] += 1
    show.counts = {
        "Catalog rows": len(rows),
        "Placed in the schematic": len({p.id for p in placements}),
        "With their own library symbol": how["own"] + how["passive"],
        "With a symbol from a board": how["board"],
        "With the slot reference's symbol": how["slot"],
        "As placeholder": how["placeholder"],
        "Further symbols of a part number": how["also"],
        "On the board": on_board,
        "Schematic only": len(placements) - on_board,
    }
    source = ", ".join(f"`{n}`" for n in SOURCES[catalog])
    out = show.folder
    files = [_file_op(out / f"{show.project}.kicad_sch", _root_text(show))]
    files += [_file_op(out / sheet.file, _sheet_text(show, sheet, lib)) for sheet in show.sheets]
    files.append(_file_op(out / f"{show.project}.kicad_pcb", board))
    files.append(_file_op(out / f"{show.project}.kicad_pro", _project_text(show), keep_existing=True))
    for kind, nickname, target, what in (
        ("sym_lib_table", lib.symbol_nickname, lib.symbol_file, "symbol"),
        ("fp_lib_table", lib.footprint_nickname, lib.pretty, "footprint"),
    ):
        uri = "${" + LIB_VAR + "}/" + target.relative_to(lib.root).as_posix()
        files.append(_file_op(out / kind.replace("_lib_", "-lib-"), _table_text(kind, nickname, uri, what)))
    files.append(_file_op(out / REPORT, _report_text(show, source)))
    files += _stale(out, {f.path.name for f in files})
    readme = folder / "README.md"
    if readme.is_file():
        with readme.open(encoding="utf-8", newline="") as f:
            original = f.read()
        updated = _readme_text(original, show)
        files.append(FileOp(readme, updated, "unchanged" if updated == original else "changed", original))
    show.files = files
    return show


def build(root: Path, settings: Settings, only: list[str] | None = None) -> tuple[Library, list[Showcase]]:
    """Plan the showcase of every catalog under ``root`` (or of ``only``). Nothing is written."""
    root = root.expanduser()
    if not root.is_dir():
        raise UsageError(f"Not a directory: {root}")
    for name in only or []:
        if name not in CATALOGS:
            raise UsageError(f"Unknown catalog {name!r}.", "One of: " + ", ".join(CATALOGS) + ".")
    folders = _classify(root, [Path(c) for c in settings.audit_catalogs])
    wanted = [c for c in CATALOGS if c in folders and (not only or c in only)]
    missing = [c for c in (only or []) if c not in folders]
    if missing or not wanted:
        raise UsageError(
            f"No {' or '.join(missing or CATALOGS)} catalog under {root}.",
            "catalogs in [audit] names " + (", ".join(settings.audit_catalogs) or "nothing") + ".",
        )
    lib = load_library(root, settings)
    if any(name != "passives" for name in wanted):
        lib.board = load_board_symbols(root, lib, tuple(folder / "showcase" for folder in folders.values()))
    catalog = load_catalog(folders.get("passives"), folders.get("ics"), folders.get("other"))
    rows = {"passives": catalog.passives, "ics": catalog.ics, "other": catalog.other}
    return lib, [_build_one(name, folders[name], rows[name], lib, settings) for name in wanted]
