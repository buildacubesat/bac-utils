def uid(*parts: str) -> str:
    """A UUID that depends on ``parts`` only, so an unchanged row keeps its identifiers."""
    return str(uuid.uuid5(NAMESPACE, "\x1f".join(parts)))


def _n(value: float) -> str:
    return fmt_number(round(value, 4), 4)


def _snap(value: float, grid: float = GRID) -> float:
    return round(round(value / grid) * grid, 4)


def _snap_up(value: float, grid: float) -> float:
    return round(math.ceil(value / grid - 1e-9) * grid, 4)


def _reindent(raw: str, levels: int) -> str:
    """``raw`` (a node whose first line carries no indentation) moved ``levels`` tab stops to the right or left."""
    lines = raw.replace("\r\n", "\n").split("\n")
    out = [lines[0]]
    for line in lines[1:]:
        if levels >= 0:
            out.append("\t" * levels + line if line.strip() else line)
        else:
            strip = 0
            while strip < -levels and line[strip : strip + 1] == "\t":
                strip += 1
            out.append(line[strip:])
    return "\n".join(out)


def _numbers(node: Node | None, count: int) -> list[float]:
    if node is None:
        return []
    values = [a.number() for a in node.atoms()[1:]]
    return [v for v in values[:count] if v is not None]


def _whole_line(text: str, node: Node) -> tuple[int, int]:
    """The span of ``node`` with the line break and indentation before it, for removing the node."""
    start = text.rfind("\n", 0, node.start)
    return (start if start >= 0 and not text[start : node.start].strip() else node.start, node.end)


def readme_version(folder: Path) -> tuple[str, str]:
    """``(version, date)`` of the newest row in the version history of ``folder/README.md``."""
    readme = folder / "README.md"
    if not readme.is_file():
        return "", ""
    rows = _VERSION_ROW.findall(readme.read_text(encoding="utf-8"))
    if not rows:
        return "", ""
    return max(rows, key=lambda r: tuple(int(x) for x in r[0].split(".")))


