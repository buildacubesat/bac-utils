def _net_escape(name: str) -> str:
    return name.replace("/", "{slash}")


def _pad_nets(placement: Placement) -> dict[str, tuple[str, str, str]]:
    """Pad number -> (net, pinfunction, pintype) as KiCad names an unconnected pin under a no-connect flag.

    ``unconnected-(R1-Pad1)`` for a pin without a name of its own, ``unconnected-(U1-CLKO-Pad2)`` for a named
    one, with the unit letter after the reference in a multi-unit symbol. Stacked pins share a net KiCad names
    itself and are left for Update PCB from Schematic.
    """
    nets: dict[str, tuple[str, str, str]] = {}
    units = sorted(placement.symbol.units)
    for unit, pins in placement.symbol.units.items():
        stacked: dict[tuple[float, float], int] = defaultdict(int)
        for pin in pins:
            stacked[(pin.x, pin.y)] += 1
        letter = chr(ord("A") + units.index(unit)) if len(units) > 1 and units.index(unit) < 26 else ""
        for pin in pins:
            if not pin.number or pin.number in nets or stacked[(pin.x, pin.y)] > 1:
                continue
            shown = pin.name not in ("", "~")
            function = f"{pin.name}_{pin.number}" if shown else ""
            if pin.hidden and pin.kind == "power_in" and shown:
                nets[pin.number] = (pin.name, function, pin.kind)
                continue
            if shown and pin.name != pin.number:
                inner = f"{placement.reference}{letter}-{_net_escape(pin.name)}-Pad{_net_escape(pin.number)}"
            else:
                inner = f"{placement.reference}-Pad{_net_escape(pin.number)}"
            kind = pin.kind if pin.kind == "no_connect" else f"{pin.kind}+no_connect"
            nets[pin.number] = (f"unconnected-({inner})", function, kind)
    return nets


