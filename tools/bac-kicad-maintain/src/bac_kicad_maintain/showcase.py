@dataclass(frozen=True, slots=True)
class Finding:
    kind: str
    row: str
    detail: str

    def as_dict(self) -> dict[str, str]:
        return {"kind": self.kind, "row": self.row, "detail": self.detail}


@dataclass(frozen=True, slots=True)
class Pin:
    number: str
    name: str
    kind: str
    hidden: bool
    x: float
    y: float


@dataclass(slots=True)
class LibSymbol:
    """A library symbol as the generator needs it: its text, its units with pins and extents."""

    name: str
    raw: str  # the (symbol …) node as written in the library, first line unindented
    properties: list[tuple[str, str, str]]  # (name, value, raw property node)
    flags: dict[str, str]
    units: dict[int, list[Pin]]
    boxes: dict[int, tuple[float, float, float, float]]  # unit -> (min x, min y, max x, max y) in sheet orientation
    nickname: str = ""  # the library of a symbol taken from a board's sheet; empty: the central library
    source: str = ""  # that sheet, relative to the repository root
    footprint: str = ""  # the footprint the board gives it

    def value(self, name: str) -> str:
        return next((v for n, v, _ in self.properties if n == name), "")


@dataclass(slots=True)
class LibFootprint:
    reference: str  # "Nickname:Name"
    text: str
    root: Node
    box: tuple[float, float, float, float]
    models: list[str]


@dataclass(slots=True)
class Placement:
    row: dict[str, str]
    symbol: LibSymbol
    how: str  # "own", "passive", "slot", "placeholder"
    value: str
    footprint: str  # the Footprint field of the instance, may be empty
    mpn: str  # written into the instance; empty for a passive
    note: str
    library: LibFootprint | None = None  # the footprint text for the board, None when schematic only
    reference: str = ""
    width: float = 0.0
    height: float = 0.0
    x: float = 0.0
    y: float = 0.0
    extra: int = 0  # 0: the row's placement; n: the n-th further symbol carrying the same part number

    @property
    def id(self) -> str:
        return self.row["id"]

    @property
    def key(self) -> str:
        """What the identifiers derive from: the row id, with a suffix for a further symbol of the same part."""
        return self.id if not self.extra else f"{self.id}#{self.extra + 1}"


@dataclass(slots=True)
class Line:
    """A labeled group of placements: a slot, or one row of a passives grid."""

    label: str
    items: list[Placement]

    @property
    def width(self) -> float:
        return max(sum(i.width for i in self.items), _snap_up(len(self.label) * 1.35 + 5.08, 2.54))

    @property
    def height(self) -> float:
        return max(i.height for i in self.items) + (LABEL_HEIGHT if self.label else 0.0)


@dataclass(slots=True)
class Sheet:
    name: str
    file: str
    paper: str
    rows: list[list[Line]]  # groups side by side, rows top to bottom
    uuid: str = ""
    symbol_uuid: str = ""  # the sheet symbol on the root sheet
    page: int = 0

    @property
    def lines(self) -> list[Line]:
        return [line for row in self.rows for line in row]

    @property
    def items(self) -> list[Placement]:
        return [p for line in self.lines for p in line.items]


@dataclass(slots=True)
class FileOp:
    path: Path
    text: str | None  # None: remove
    state: str  # "new", "changed", "unchanged", "kept", "remove"
    original: str | None = None
    done: bool = False  # written or removed by this run


