def _readme_text(original: str, show: Showcase) -> str:
    """``original`` with the marked showcase block refreshed, or added: under "Files", else before the history."""
    eol = "\r\n" if "\r\n" in original else "\n"

    def block(heading: bool) -> str:
        return readme_section(show, heading).replace("\n", eol)

    begin, end = original.find(README_BEGIN), original.find(README_END)
    if (begin >= 0) != (end >= 0) or end < begin:
        raise ShowcaseError(
            "The catalog README has half a showcase block.",
            f"Restore or remove the marker lines in {show.folder.parent / 'README.md'}.",
        )
    if begin >= 0:
        return original[:begin] + block("## Showcase" in original[begin:end]) + original[end + len(README_END) :]
    headings, fenced = [], False
    for match in re.finditer(r"^(```|~~~|## ).*$", original, re.M):
        if match.group(1) != "## ":
            fenced = not fenced
        elif not fenced:
            headings.append(match)
    files = next((i for i, m in enumerate(headings) if re.fullmatch(r"## (\d+\. )?Files", m.group(0).strip())), None)
    if files is not None:
        cut = headings[files + 1].start() if files + 1 < len(headings) else len(original)
        return original[:cut].rstrip("\r\n") + eol * 2 + block(False) + eol * 2 + original[cut:]
    history = next((m for m in headings if "version history" in m.group(0).lower()), None)
    if history is not None:
        cut = history.start()
        return original[:cut].rstrip("\r\n") + eol * 2 + block(True) + eol * 2 + original[cut:]
    return original.rstrip("\r\n") + eol * 2 + block(True) + eol


