def _board_footprint(show: Showcase, sheet: Sheet, placement: Placement, x: float, y: float) -> str:
    fp = placement.library
    assert fp is not None
    text, root = fp.text, fp.root
    key = f"{show.catalog}/{placement.key}"
    edits: list[tuple[int, int, str]] = []
    name = root.atoms()[1]
    edits.append((name.start, name.end, quoted(fp.reference)))
    for head in ("version", "generator", "generator_version", "tedit", "at", "uuid", "path", "sheetname", "sheetfile"):
        for child in root.children(head):
            edits.append((*_whole_line(text, child), ""))
    layer = root.child("layer")
    anchor = layer.end if layer is not None else name.end
    first_unit = min(placement.symbol.boxes)
    symbol_uuid = uid("symbol", show.catalog, f"{placement.key}/{first_unit}")
    edits.append((anchor, anchor, f"\n\t(uuid {quoted(uid('fp', key))})\n\t(at {_n(x)} {_n(y)})"))
    values = {
        "Reference": placement.reference,
        "Value": placement.value,
        "Datasheet": placement.symbol.value("Datasheet"),
        "Description": placement.symbol.value("Description"),
    }
    last_property = None
    for prop in root.children("property"):
        atoms = prop.atoms()
        if len(atoms) < 3:
            continue
        last_property = prop
        if atoms[1].value in values:
            edits.append((atoms[2].start, atoms[2].end, quoted(values[atoms[1].value])))
    extra = []
    if placement.mpn:
        extra.append(_board_property("Manufacturer PN", placement.mpn, key))
    extra += [
        f"\t(path {quoted('/' + sheet.symbol_uuid + '/' + symbol_uuid)})",
        f"\t(sheetname {quoted('/' + sheet.name + '/')})",
        f"\t(sheetfile {quoted(sheet.file)})",
    ]
    after = last_property.end if last_property is not None else anchor
    edits.append((after, after, "\n" + "\n".join(extra)))
    for zone in root.children("zone"):
        for stale in ("net", "net_name"):  # a footprint saved by KiCad 9 numbers its keepout's net; KiCad 10 names none
            for child in zone.children(stale):
                edits.append((*_whole_line(text, child), ""))
        # A board keeps a footprint's zones in board coordinates, unlike its pads and graphics: move the outline along.
        for node in zone.walk():
            if node.head in ("xy", "start", "mid", "end") and len(_numbers(node, 2)) == 2:
                px, py = _numbers(node, 2)
                edits.append((node.start, node.end, f"({node.head} {_n(px + x)} {_n(py + y)})"))
    ordinal = 0
    for node in root.walk():
        if node.head == "uuid" and node is not root.child("uuid"):
            ordinal += 1
            atoms = node.atoms()
            if len(atoms) > 1:
                edits.append((atoms[1].start, atoms[1].end, quoted(uid("fp", key, str(ordinal)))))
    nets = _pad_nets(placement)
    for pad in root.children("pad"):
        number = pad.value(1)
        if number not in nets:
            continue
        net, function, kind = nets[number]
        lines = [f"(net {quoted(net)})"] + ([f"(pinfunction {quoted(function)})"] if function else [])
        lines.append(f"(pintype {quoted(kind)})")
        for stale in ("net", "pinfunction", "pintype"):
            for child in pad.children(stale):
                edits.append((*_whole_line(text, child), ""))
        own = pad.child("uuid")
        if own is not None:
            edits.append((own.start, own.start, "".join(line + "\n\t\t" for line in lines)))
        else:
            edits.append((pad.end - 1, pad.end - 1, "\t" + "\n\t\t".join(lines) + "\n\t"))
    return "\t" + _reindent(
        apply_edits(text[root.start : root.end], [(s - root.start, e - root.start, r) for s, e, r in edits]), 1
    )


def _board_text(show: Showcase, settings: Settings) -> tuple[str, int]:
    x0, y0 = BOARD_ORIGIN
    body: list[str] = []
    y = y0
    right = x0 + BOARD_WIDTH
    placed = 0
    for sheet in show.sheets:
        items = [p for p in sheet.items if p.library is not None]
        if not items:
            continue
        body.append(
            f"\t(gr_text {quoted(sheet.name)}\n\t\t(at {_n(x0 + len(sheet.name) * 0.35)} {_n(y + 1.5)} 0)\n"
            f'\t\t(layer "F.SilkS")\n'
            f"\t\t(uuid {quoted(uid('board', show.catalog, 'title', sheet.file))})\n\t\t(effects\n\t\t\t(font\n"
            "\t\t\t\t(size 0.8 0.8)\n\t\t\t\t(thickness 0.1)\n\t\t\t)\n\t\t)\n\t)"
        )
        y += 5.0
        x, tallest = x0, 0.0
        for item in items:
            box = item.library.box
            w, h = box[2] - box[0], box[3] - box[1]
            if x > x0 and x + w > right:
                x, y, tallest = x0, y + tallest + BOARD_GAP, 0.0
            body.append(_board_footprint(show, sheet, item, round(x - box[0], 3), round(y - box[1], 3)))
            placed += 1
            right = max(right, x + w)
            x += w + BOARD_GAP
            tallest = max(tallest, h)
        y += tallest + 2 * BOARD_GAP
    body.append(
        f"\t(gr_rect\n\t\t(start {_n(x0 - 5)} {_n(y0 - 5)})\n\t\t(end {_n(right + 5)} {_n(y + 2)})\n"
        '\t\t(stroke\n\t\t\t(width 0.1)\n\t\t\t(type default)\n\t\t)\n\t\t(fill no)\n\t\t(layer "Edge.Cuts")\n'
        f"\t\t(uuid {quoted(uid('board', show.catalog, 'edge'))})\n\t)"
    )
    paper = next((p[0] for p in PAPERS if right + 20 <= p[1] and y + 20 <= p[2]), "A0")
    head = [
        "(kicad_pcb",
        f"\t(version {PCB_VERSION})",
        f"\t(generator {quoted(GENERATOR)})",
        '\t(generator_version "10.0")',
        "\t(general\n\t\t(thickness 1.6)\n\t\t(legacy_teardrops no)\n\t)",
        f"\t(paper {quoted(paper)})",
        _title_block(show),
        _LAYERS,
    ]
    text = "\n".join(head + body + ["\t(embedded_fonts no)", ")"]) + "\n"
    selected = settings.enabled() & {"text", "courtyards"}
    if selected:
        text = transform(text, parse(text), settings, "apply", selected, where="showcase board").text
    return text, placed


