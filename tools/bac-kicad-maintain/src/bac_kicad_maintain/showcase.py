def _passive_placement(lib: Library, row: dict[str, str], findings: list[Finding]) -> Placement:
    kind = row.get("_kind", "r")
    four = row.get("terminals", "") == "4" or row.get("role") == "shunt"
    polarized = kind == "c" and "Tantalum" in row.get("footprint", "")
    if kind == "r":
        name = "bac R Shunt" if four else "bac R"
        stem = f"R-Shunt-{row['package']}-4T" if four else f"R-{row['package']}"
    else:
        name = "bac C Polarized" if polarized and "bac C Polarized" in lib.raw else "bac C"
        stem = f"C-{row['package']}"
    footprint = f"{lib.footprint_nickname}:{stem}"
    if lib.footprint(footprint) is None:
        twin = (lib.pretty / (UNUSED_FILE + stem + FOOTPRINT_SUFFIX)).is_file()
        fallback = row.get("footprint", "")
        detail = f"the bac library has no {stem}" + (f" (it has {UNUSED_FILE}{stem})" if twin else "")
        footprint = fallback
        findings.append(Finding("no bac footprint", row["id"], detail + (f"; placed {fallback}" if fallback else "")))
    note = "\n".join([row["id"], f"{row.get('grade', '')} {row.get('role', '')}".strip(), _qualified(row, "status")])
    return Placement(row, lib.symbol(name), "passive", row["value"], footprint, "", note)


def _qualified(row: dict[str, str], extra: str) -> str:
    parts = [row.get("qualification", ""), row.get(extra, "")]
    return " · ".join(p for p in parts if p)


def _live(lib: Library, mpn: str) -> tuple[list[str], list[str]]:
    names = lib.by_mpn.get(mpn.strip().casefold(), []) if mpn.strip() else []
    return [n for n in names if not n.startswith(UNUSED_SYMBOL)], [n for n in names if n.startswith(UNUSED_SYMBOL)]


def _own_symbols(lib: Library, row: dict[str, str]) -> list[str]:
    """The live symbols carrying the row's part number: the one on the row's footprint first, then the others."""
    live, _ = _live(lib, row["mpn"])
    wanted = row.get("footprint", "")
    first = next((n for n in live if wanted and lib.symbol(n).value("Footprint") == wanted), live[0] if live else None)
    return [first] + [n for n in live if n != first] if first else []


def _own_symbol(lib: Library, row: dict[str, str]) -> str | None:
    return next(iter(_own_symbols(lib, row)), None)


def _board_symbol(lib: Library, row: dict[str, str]) -> LibSymbol | None:
    return lib.board.get(row["mpn"].strip().casefold()) if row["mpn"].strip() else None


def _row_symbol(lib: Library, row: dict[str, str] | None) -> LibSymbol | None:
    """The symbol a row is drawn with by itself: the central library's, else the one a board uses."""
    if row is None:
        return None
    own = _own_symbol(lib, row)
    return lib.symbol(own) if own is not None else _board_symbol(lib, row)


def _part_placement(
    lib: Library, row: dict[str, str], reference: LibSymbol | None, findings: list[Finding]
) -> Placement:
    own = _own_symbol(lib, row)
    board = _board_symbol(lib, row) if own is None else None
    footprint = row.get("footprint", "")
    if own is not None or board is not None:
        symbol, how = (lib.symbol(own), "own") if own is not None else (board, "board")
        shown = repr(own) if own is not None else f"{_lib_id(lib, symbol)} on {symbol.source}"
        default = symbol.value("Footprint") if own is not None else symbol.footprint
        if board is not None:
            findings.append(Finding("board symbol", row["id"], shown))
        if not footprint and default:
            footprint = default
            findings.append(Finding("footprint from symbol", row["id"], f"{default} from {shown}"))
        elif footprint and default and footprint != default:
            findings.append(Finding("footprint differs", row["id"], f"row {footprint}; symbol {shown} {default}"))
    elif reference is not None and row.get("compat") in DROP_IN:
        symbol, how = reference, "slot"
    else:
        symbol, how = lib.symbol(PLACEHOLDER), "placeholder"
        _, parked = _live(lib, row["mpn"])
        detail = f"the library has it as {parked[0]!r}" if parked else f"no symbol carries {row['mpn']}"
        findings.append(Finding("symbol #unused" if parked else "no symbol", row["id"], detail))
    value = symbol.value("Value") if how != "placeholder" else row["mpn"]
    middle = row.get("role", "") + (f" · {row['compat']}" if row.get("compat") not in ("", "reference") else "")
    note = "\n".join([row["id"], middle, _qualified(row, "lifecycle")])
    return Placement(row, symbol, how, value, footprint, row["mpn"], note)


def _lib_id(lib: Library, symbol: LibSymbol) -> str:
    return f"{symbol.nickname or lib.symbol_nickname}:{symbol.name}"


def _further_placements(lib: Library, row: dict[str, str], findings: list[Finding]) -> list[Placement]:
    """One part number on several live symbols (a connector drawn per function): each further symbol is placed too."""
    out = []
    for index, name in enumerate(_own_symbols(lib, row)[1:], start=1):
        symbol = lib.symbol(name)
        note = "\n".join([row["id"], f"also {name}", _qualified(row, "lifecycle")])
        out.append(
            Placement(
                row, symbol, "also", symbol.value("Value"), symbol.value("Footprint"), row["mpn"], note, extra=index
            )
        )
        findings.append(Finding("further symbol", row["id"], f"{name!r} carries the same part number; placed too"))
    return out


def _resolve_footprint(lib: Library, placement: Placement, findings: list[Finding]) -> None:
    row, reference = placement.row, placement.footprint
    if placement.symbol.flags.get("on_board") == "no":
        findings.append(Finding("no footprint", row["id"], f"the symbol {placement.symbol.name!r} is not on the board"))
        return
    if not reference:
        why = ", ".join(v for v in (row.get("role", ""), row.get("compat", "")) if v and v != "reference")
        findings.append(Finding("no footprint", row["id"], why or "the row names none"))
        return
    nickname, _, name = reference.partition(":")
    found = lib.footprint(reference)
    if found is None:
        if nickname == lib.footprint_nickname:
            twin = (lib.pretty / (UNUSED_FILE + name + FOOTPRINT_SUFFIX)).is_file()
            detail = (
                f"the bac library has it as {UNUSED_FILE}{name}" if twin else f"{reference} is not in the bac library"
            )
        elif lib.stock is None:
            detail = f"{reference}: no KiCad footprint folder configured ([showcase] kicad_footprints)"
        else:
            detail = f"{reference} is not under {lib.stock}"
        findings.append(Finding("footprint missing", row["id"], detail))
        return
    placement.library = found
    if nickname != lib.footprint_nickname and placement.how != "passive":
        findings.append(Finding("stock footprint", row["id"], reference))
    ours = [m for m in found.models if "${" + LIB_VAR + "}" in m or not _VAR.search(m)]
    if not found.models:
        findings.append(Finding("no 3D model", row["id"], f"{reference} names no model"))
    for model in ours:
        path = Path(model.replace("${" + LIB_VAR + "}", lib.root.as_posix()))
        if path.resolve().as_posix() not in lib.models and not path.is_file():
            findings.append(Finding("3D model missing", row["id"], f"{reference} points at {model}"))


def _passive_key(row: dict[str, str]) -> tuple:
    value = row.get("_value")
    return (
        value if value is not None else math.inf,
        row["package"],
        _ROLE_ORDER.get(row.get("role", ""), 9),
        row["id"],
    )


def _slot_lines(rows: list[dict[str, str]], lib: Library, findings: list[Finding]) -> list[Line]:
    slots: dict[str, list[dict[str, str]]] = {}
    for row in rows:
        slots.setdefault(row["slot"], []).append(row)
    lines = []
    for slot, group in slots.items():
        group = sorted(group, key=lambda r: _ROLE_ORDER.get(r.get("role", ""), 9))
        reference_row = next((r for r in group if r.get("role") == "reference"), None)
        reference = _row_symbol(lib, reference_row)
        function = (reference_row or group[0]).get("function", "")
        label = f"{slot} – {function}" if function else slot
        items: list[Placement] = []
        for r in group:
            items.append(_part_placement(lib, r, reference, findings))
            items += _further_placements(lib, r, findings)
        lines.append(Line(label, items))
    return lines


