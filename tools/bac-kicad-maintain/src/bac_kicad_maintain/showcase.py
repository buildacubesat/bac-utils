def _measure(placement: Placement, passive: bool) -> None:
    boxes = placement.symbol.boxes
    width = sum(b[2] - b[0] for b in boxes.values()) + 7.62 * (len(boxes) - 1)
    height = max(b[3] - b[1] for b in boxes.values())
    note_lines = placement.note.split("\n")
    note_width = max(len(line) for line in note_lines) * NOTE_SIZE * 0.9
    if passive:
        placement.width = max(PASSIVE_PITCH, _snap_up(max(width + 10.16, note_width + 2.54), PASSIVE_PITCH))
        placement.height = PASSIVE_PITCH
    else:
        placement.width = _snap_up(max(width + 20.32, note_width + 5.08, PASSIVE_PITCH), 2.54)
        placement.height = _snap_up(height + len(note_lines) * NOTE_LINE + 15.24, 2.54)


def _usable(paper: tuple[str, float, float]) -> tuple[float, float]:
    return paper[1] - 2 * MARGIN, paper[2] - MARGIN - FOOTER


def _wrap(lines: list[Line], width: float) -> list[Line]:
    """Break lines wider than ``width``; a continuation keeps the label with an arrow."""
    out: list[Line] = []
    for line in lines:
        current: list[Placement] = []
        used = 0.0
        first = True
        for item in line.items:
            if current and used + item.width > width:
                out.append(Line(line.label if first else f"{line.label} →", current))
                current, used, first = [], 0.0, False
            current.append(item)
            used += item.width
        if current:
            out.append(Line(line.label if first else f"{line.label} →", current))
    return out


def _paginate(lines: list[Line], *, merge: bool) -> list[tuple[str, list[list[Line]]]]:
    """Flow groups onto A3 pages, several to a row when ``merge``; a group too large for A3 gets the smallest
    paper it fits, on its own page."""
    a3_w, a3_h = _usable(PAPERS[0])
    rows: list[list[Line]] = []
    for line in _wrap(lines, a3_w):
        if merge and rows and sum(g.width for g in rows[-1]) + line.width <= a3_w:
            rows[-1].append(line)
        else:
            rows.append([line])
    pages: list[tuple[str, list[list[Line]]]] = []
    current: list[list[Line]] = []
    used = 0.0
    for row in rows:
        w, h = sum(g.width for g in row), max(g.height for g in row)
        if w > a3_w or h > a3_h:
            if current:
                pages.append(("A3", current))
                current, used = [], 0.0
            paper = next((p for p in PAPERS if w <= _usable(p)[0] and h <= _usable(p)[1]), PAPERS[-1])
            pages.append((paper[0], [row]))
            continue
        if current and used + h > a3_h:
            pages.append(("A3", current))
            current, used = [], 0.0
        current.append(row)
        used += h
    if current:
        pages.append(("A3", current))
    return pages


def _position(sheet: Sheet) -> None:
    y = MARGIN
    for row in sheet.rows:
        x = MARGIN
        labeled = any(line.label for line in row)
        top = y + (LABEL_HEIGHT if labeled else 0.0)
        for line in row:
            start = x
            for item in line.items:
                item.x, item.y = x, top
                x += item.width
            x = start + line.width
        y += (
            max(line.height for line in row)
            if not labeled
            else LABEL_HEIGHT + max(i.height for g in row for i in g.items)
        )


def _passive_sheets(rows: list[dict[str, str]], lib: Library, findings: list[Finding]) -> list[Sheet]:
    sheets: list[Sheet] = []
    columns = int(_usable(PAPERS[0])[0] // PASSIVE_PITCH)
    for kind, title in (("r", "Resistors"), ("c", "Capacitors")):
        for grade in ("dev", "flight"):
            group = sorted((r for r in rows if r.get("_kind") == kind and r.get("grade") == grade), key=_passive_key)
            if not group:
                continue
            items = [_passive_placement(lib, r, findings) for r in group]
            for item in items:
                _measure(item, passive=True)
            lines, current, used = [], [], 0.0
            for item in items:
                if current and used + item.width > columns * PASSIVE_PITCH:
                    lines.append(Line("", current))
                    current, used = [], 0.0
                current.append(item)
                used += item.width
            if current:
                lines.append(Line("", current))
            for index, (paper, page) in enumerate(_paginate(lines, merge=False), start=1):
                suffix = "" if index == 1 else f" {index}"
                name = f"{title} {grade.capitalize()}{suffix}"
                sheets.append(Sheet(name, name.lower().replace(" ", "-") + ".kicad_sch", paper, page))
    known = {id(p.row) for s in sheets for p in s.items}
    for row in rows:
        if id(row) not in known:
            findings.append(
                Finding("not placed", row["id"], f"grade {row.get('grade', '')!r} is neither dev nor flight")
            )
    return sheets


def _part_sheets(catalog: str, rows: list[dict[str, str]], lib: Library, findings: list[Finding]) -> list[Sheet]:
    lines = _slot_lines(rows, lib, findings)
    for line in lines:
        for item in line.items:
            _measure(item, passive=False)
    title = "ICs" if catalog == "ics" else "Other Parts"
    stem = "ics" if catalog == "ics" else "other"
    return [
        Sheet(f"{title} {index}", f"{stem}-{index:02d}.kicad_sch", paper, page)
        for index, (paper, page) in enumerate(_paginate(lines, merge=True), start=1)
    ]


def _annotate(sheets: list[Sheet]) -> None:
    counters: dict[str, int] = defaultdict(int)
    for sheet in sheets:
        for item in sheet.items:
            prefix = item.symbol.value("Reference").rstrip("?*") or "X"
            counters[prefix] += 1
            item.reference = f"{prefix}{counters[prefix]}"


