def _extent(points: list[tuple[float, float]]) -> tuple[float, float, float, float]:
    if not points:
        return (-2.54, -2.54, 2.54, 2.54)
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    return (min(xs), min(ys), max(xs), max(ys))


def _graphic_points(node: Node) -> list[tuple[float, float]]:
    """The points a graphic item of a symbol or footprint spans, in the file's own coordinates."""
    points: list[tuple[float, float]] = []
    for key in ("start", "end", "mid"):
        xy = _numbers(node.child(key), 2)
        if len(xy) == 2:
            points.append((xy[0], xy[1]))
    center = _numbers(node.child("center"), 2)
    if len(center) == 2:
        radius = _numbers(node.child("radius"), 1)
        end = _numbers(node.child("end"), 2)
        r = radius[0] if radius else (math.dist(center, end) if len(end) == 2 else 0.0)
        points += [(center[0] - r, center[1] - r), (center[0] + r, center[1] + r)]
    pts = node.child("pts")
    if pts is not None:
        for xy_node in pts.children("xy"):
            xy = _numbers(xy_node, 2)
            if len(xy) == 2:
                points.append((xy[0], xy[1]))
    return points


def _unit_of(name: str, parent: str) -> int:
    match = re.fullmatch(r"_(\d+)_(\d+)", name[len(parent) :]) if name.startswith(parent) else None
    return int(match.group(1)) if match else -1


def _style_of(name: str) -> int:
    return int(name.rsplit("_", 1)[1]) if name.rsplit("_", 1)[-1].isdigit() else 1


def read_symbol(name: str, raw: str) -> LibSymbol:
    """Parse one ``(symbol …)`` node (``raw``) into pins and extents per unit."""
    node = parse(raw, where=f"symbol {name}")
    properties = []
    for prop in node.children("property"):
        atoms = prop.atoms()
        if len(atoms) >= 3 and atoms[1].quoted:  # not KiCad's (property private "KLC_…" …)
            properties.append((atoms[1].value, atoms[2].value, raw[prop.start : prop.end]))
    flags = {}
    for key in ("exclude_from_sim", "in_bom", "on_board", "in_pos_files"):
        child = node.child(key)
        flags[key] = child.value(1) if child else "yes"
    pins: dict[int, list[Pin]] = defaultdict(list)
    points: dict[int, list[tuple[float, float]]] = defaultdict(list)
    for sub in node.children("symbol"):
        unit = _unit_of(sub.value(1), name)
        if unit < 0 or _style_of(sub.value(1)) > 1:
            continue
        for item in sub.items:
            if not isinstance(item, Node):
                continue
            if item.head == "pin":
                at = _numbers(item.child("at"), 3)
                if len(at) < 2:
                    continue
                angle = at[2] if len(at) > 2 else 0.0
                length = (_numbers(item.child("length"), 1) or [0.0])[0]
                kind = item.value(1)
                hide = item.child("hide")
                hidden = (hide is not None and hide.value(1) != "no") or any(a.value == "hide" for a in item.atoms())
                number = item.child("number")
                pin_name = item.child("name")
                pins[unit].append(
                    Pin(
                        number.value(1) if number else "",
                        pin_name.value(1) if pin_name else "",
                        kind,
                        hidden,
                        at[0],
                        -at[1],
                    )
                )
                rad = math.radians(angle)
                points[unit] += [(at[0], -at[1]), (at[0] + length * math.cos(rad), -(at[1] + length * math.sin(rad)))]
            else:
                points[unit] += [(x, -y) for x, y in _graphic_points(item)]
    numbers = sorted(u for u in set(pins) | set(points) if u > 0) or [1]
    units = {u: pins.get(0, []) + pins.get(u, []) for u in numbers}
    boxes = {u: _extent(points.get(0, []) + points.get(u, [])) for u in numbers}
    return LibSymbol(name, raw, properties, flags, units, boxes)


def _footprint_box(root: Node) -> tuple[float, float, float, float]:
    courtyard: list[tuple[float, float]] = []
    everything: list[tuple[float, float]] = []
    for item in root.items:
        if not isinstance(item, Node):
            continue
        if item.head in ("fp_line", "fp_rect", "fp_poly", "fp_circle", "fp_arc"):
            points = _graphic_points(item)
            layer = item.child("layer")
            (courtyard if layer and layer.value(1).endswith(".CrtYd") else everything).extend(points)
        elif item.head == "pad":
            at, size = _numbers(item.child("at"), 3), _numbers(item.child("size"), 2)
            if len(at) >= 2 and len(size) == 2:
                w, h = (size[1], size[0]) if len(at) > 2 and round(at[2]) % 180 == 90 else (size[0], size[1])
                everything += [(at[0] - w / 2, at[1] - h / 2), (at[0] + w / 2, at[1] + h / 2)]
    return _extent(courtyard + everything)  # a courtyard may cover the body only (a board-to-board connector)


@dataclass(slots=True)
class Library:
    root: Path  # resources/kicad-libraries
    symbol_file: Path
    symbol_text: str
    symbol_nickname: str
    footprint_nickname: str
    pretty: Path
    stock: Path | None
    raw: dict[str, str]  # symbol name -> node text
    by_mpn: dict[str, list[str]]
    models: set[str]
    board: dict[str, LibSymbol] = field(default_factory=dict)  # part number (casefolded) -> the symbol a board uses
    _symbols: dict[str, LibSymbol] = field(default_factory=dict)
    _footprints: dict[str, LibFootprint | None] = field(default_factory=dict)

    def symbol(self, name: str) -> LibSymbol:
        if name not in self._symbols:
            raw = self.raw.get(name) or (PLACEHOLDER_SYMBOL if name == PLACEHOLDER else None)
            if raw is None:
                raise ShowcaseError(f"The symbol library has no {name!r}.", f"In {self.symbol_file}.")
            self._symbols[name] = read_symbol(name, raw)
        return self._symbols[name]

    def footprint_path(self, reference: str) -> Path | None:
        nickname, _, name = reference.partition(":")
        if not name:
            return None
        if nickname == self.footprint_nickname:
            return self.pretty / (name + FOOTPRINT_SUFFIX)
        return self.stock / (nickname + ".pretty") / (name + FOOTPRINT_SUFFIX) if self.stock else None

    def footprint(self, reference: str) -> LibFootprint | None:
        if reference not in self._footprints:
            path = self.footprint_path(reference)
            loaded = None
            if path is not None and path.is_file():
                text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
                root = parse(text, where=str(path))
                if root.head != "footprint":
                    raise ShowcaseError(f"{path}: not a footprint (the file starts with ({root.head} …)).")
                models = [m.value(1) for m in root.children("model") if m.value(1)]
                loaded = LibFootprint(reference, text, root, _footprint_box(root), models)
            self._footprints[reference] = loaded
        return self._footprints[reference]


def load_library(root: Path, settings: Settings) -> Library:
    library = Path(settings.audit_library)
    library = library if library.is_absolute() else root / library
    if not library.is_dir():
        raise UsageError(f"No library folder at {library}.", "Set [audit] library to the folder with symbols/.")
    symbol_files = _walk_files(library, (".kicad_sym",))
    if len(symbol_files) != 1:
        raise UsageError(f"Expected one symbol library under {library}, found {len(symbol_files)}.")
    text, _, symbols = _read_symbols(symbol_files[0])
    pretties = sorted(
        {p.parent for p in _walk_files(library, (FOOTPRINT_SUFFIX,)) if p.parent.name.endswith(".pretty")}
    )
    if len(pretties) != 1:
        raise UsageError(f"Expected one .pretty folder under {library}, found {len(pretties)}.")
    by_mpn: dict[str, list[str]] = defaultdict(list)
    for name, sym in sorted(symbols.items()):
        mpn = sym.properties.get("Manufacturer PN", "").strip().casefold()
        if mpn:
            by_mpn[mpn].append(name)
    models = {
        p.resolve().as_posix()
        for p in _walk_files(library, MODEL_SUFFIXES)
        if ".pretty" not in p.parts and ".kicad_blocks" not in p.parts
    }
    stock = Path(settings.showcase_kicad_footprints).expanduser() if settings.showcase_kicad_footprints else None
    return Library(
        root=library,
        symbol_file=symbol_files[0],
        symbol_text=text,
        symbol_nickname=settings.showcase_symbol_library,
        footprint_nickname=settings.showcase_footprint_library,
        pretty=pretties[0],
        stock=stock if stock and stock.is_dir() else None,
        raw={name: text[sym.node.start : sym.node.end].replace("\r\n", "\n") for name, sym in symbols.items()},
        by_mpn=dict(by_mpn),
        models=models,
    )


def load_board_symbols(root: Path, lib: Library, skip: tuple[Path, ...] = ()) -> dict[str, LibSymbol]:
    """The symbol each part number is drawn with on the repository's own sheets.

    Many catalog parts have no symbol in the central library: a board draws them with a KiCad stock symbol and
    writes the part number into the instance. Every sheet under ``root`` is read – not the showcase projects
    themselves (the folders in ``skip``, and any sheet this tool generated), not frozen copies – and a placed
    symbol with a ``Manufacturer PN`` yields that symbol from a sheet's cache, so no stock library has to be
    installed. Of several symbols for one part number the one placed most often wins (first units counted),
    then the first by name. A symbol's text is the cache entry of the first sheet by path that has it, the same
    for every part number drawn with it; the footprint is the one most of its instances carry.

    Left out: the placeholder, a symbol KiCad cached as a modified copy (``lib_name``), and a central-library
    name that is not a live symbol there – a parked or renamed one stays a finding for a person.
    """
    marker = f"(generator {quoted(GENERATOR)})"
    skipped = [Path(folder).resolve() for folder in skip]
    seen: dict[str, dict[str, list[tuple[str, str]]]] = defaultdict(lambda: defaultdict(list))
    texts: dict[str, tuple[str, str]] = {}
    for path in _walk_files(root, (".kicad_sch",)):
        rel = path.relative_to(root)
        if any("-frozen-" in part for part in rel.parts[:-1]):
            continue
        if any(path.resolve().is_relative_to(folder) for folder in skipped):
            continue
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if marker in text[:400]:
            continue
        sheet = parse(text, where=str(path))
        cache = sheet.child("lib_symbols")
        cached = {s.value(1): s for s in cache.children("symbol")} if cache is not None else {}
        for instance in sheet.children("symbol"):
            lib_id = instance.child("lib_id")
            if lib_id is None or lib_id.value(1) not in cached or instance.child("lib_name") is not None:
                continue
            key = lib_id.value(1)
            nickname, _, name = key.partition(":")
            if not name or name == PLACEHOLDER:
                continue
            if nickname == lib.symbol_nickname and (name not in lib.raw or name.startswith(UNUSED_SYMBOL)):
                continue
            unit = instance.child("unit")
            if unit is not None and unit.value(1) != "1":
                continue
            fields = {p.value(1): p.value(2) for p in instance.children("property") if len(p.atoms()) >= 3}
            mpn = fields.get("Manufacturer PN", "").strip().casefold()
            if not mpn:
                continue
            seen[mpn][key].append((rel.as_posix(), fields.get("Footprint", "").strip()))
            if key not in texts or rel.as_posix() < texts[key][0]:
                node = cached[key]
                texts[key] = (rel.as_posix(), _reindent(text[node.start : node.end], -1))
    symbols: dict[str, LibSymbol | None] = {}
    out: dict[str, LibSymbol] = {}
    for mpn, by_id in seen.items():
        lib_id = min(by_id, key=lambda key: (-len(by_id[key]), key))
        if lib_id not in symbols:
            symbols[lib_id] = _board_symbol_of(lib, lib_id, texts[lib_id][1])
        base = symbols[lib_id]
        if base is None:
            continue
        placed = by_id[lib_id]
        counts: dict[str, int] = defaultdict(int)
        for _, footprint in placed:
            if footprint:
                counts[footprint] += 1
        first = {fp: min(sheet for sheet, f in placed if f == fp) for fp in counts}
        footprint = min(counts, key=lambda fp: (-counts[fp], first[fp], fp)) if counts else ""
        out[mpn] = replace(base, source=min(sheet for sheet, _ in placed), footprint=footprint)
    return out


def _board_symbol_of(lib: Library, lib_id: str, raw: str) -> LibSymbol | None:
    nickname, _, name = lib_id.partition(":")
    if nickname == lib.symbol_nickname:
        return read_symbol(name, lib.raw[name])  # the library's own text, not a sheet's older copy
    head = f"(symbol {quoted(lib_id)}"
    if not raw.startswith(head):
        return None
    symbol = read_symbol(name, f"(symbol {quoted(name)}" + raw[len(head) :])
    symbol.nickname = nickname
    return symbol


def ensure_placeholder(library: Library) -> str | None:
    """The symbol library's text with the placeholder symbol added in name order, or ``None`` when it has it."""
    if PLACEHOLDER in library.raw:
        return None
    text = library.symbol_text
    root = parse(text, where=str(library.symbol_file))
    symbols = root.children("symbol")
    after = next((s for s in symbols if s.value(1) > PLACEHOLDER), None)
    eol = "\r\n" if "\r\n" in text else "\n"
    block = PLACEHOLDER_SYMBOL.replace("\n", eol)
    if after is not None:
        return text[: after.start] + block + eol + "\t" + text[after.start :]
    last = symbols[-1].end if symbols else root.end - 1
    return text[:last] + eol + "\t" + block + text[last:]


